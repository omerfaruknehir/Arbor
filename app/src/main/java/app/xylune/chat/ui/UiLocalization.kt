import androidx.compose.runtime.Composable
import androidx.compose.runtime.compositionLocalOf
import app.xylune.chat.settings.AppLanguage
import java.util.Locale

internal enum class XyluneUiLanguage { ENGLISH, TURKISH }

internal val LocalXyluneUiLanguage = compositionLocalOf { XyluneUiLanguage.ENGLISH }

internal fun resolvedUiLanguage(preference: AppLanguage, systemLanguage: String = Locale.getDefault().language): XyluneUiLanguage =
    when (preference) {
        AppLanguage.TURKISH -> XyluneUiLanguage.TURKISH
        AppLanguage.ENGLISH -> XyluneUiLanguage.ENGLISH
        AppLanguage.SYSTEM -> if (systemLanguage.equals("tr", ignoreCase = true)) XyluneUiLanguage.TURKISH else XyluneUiLanguage.ENGLISH
    }

@Composable
internal fun uiText(value: String): String = localizeUiText(value, LocalXyluneUiLanguage.current)

internal fun localizeUiText(value: String, language: XyluneUiLanguage): String {
    if (language != XyluneUiLanguage.TURKISH || value.isBlank()) return value
    val first = value.indexOfFirst { !it.isWhitespace() }
    if (first < 0) return value
    val last = value.indexOfLast { !it.isWhitespace() }
    val prefix = value.substring(0, first)
    val core = value.substring(first, last + 1)
    val suffix = value.substring(last + 1)
    val translated = TURKISH_UI_STRINGS[core] ?: localizeTurkishDynamic(core)
    return prefix + translated + suffix
}

